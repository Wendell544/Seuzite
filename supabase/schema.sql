-- Leitura pública (o site precisa destes dados)
drop policy if exists "public read services"      on public.services;
drop policy if exists "public read hours"         on public.business_hours;
drop policy if exists "public read blocked"       on public.blocked_dates;
drop policy if exists "public read professionals" on public.professionals;
drop policy if exists "public read settings"      on public.settings;
create policy "public read services"      on public.services       for select using (true);
create policy "public read hours"         on public.business_hours for select using (true);
create policy "public read blocked"       on public.blocked_dates  for select using (true);
create policy "public read professionals" on public.professionals  for select using (true);
create policy "public read settings"      on public.settings       for select using (true);

-- Admin escreve tudo
drop policy if exists "admin write services"      on public.services;
drop policy if exists "admin write hours"         on public.business_hours;
drop policy if exists "admin write blocked"       on public.blocked_dates;
drop policy if exists "admin write professionals" on public.professionals;
drop policy if exists "admin write settings"      on public.settings;
create policy "admin write services"      on public.services       for all using (public.is_admin()) with check (public.is_admin());
create policy "admin write hours"         on public.business_hours for all using (public.is_admin()) with check (public.is_admin());
create policy "admin write blocked"       on public.blocked_dates  for all using (public.is_admin()) with check (public.is_admin());
create policy "admin write professionals" on public.professionals  for all using (public.is_admin()) with check (public.is_admin());
create policy "admin write settings"      on public.settings       for all using (public.is_admin()) with check (public.is_admin());

-- Bookings: só o admin lê e altera. O público NÃO insere direto:
-- agenda só pelo RPC create_booking (que valida tudo).
drop policy if exists "public create booking" on public.bookings;
drop policy if exists "admin read bookings"   on public.bookings;
drop policy if exists "admin write bookings"  on public.bookings;
create policy "admin write bookings" on public.bookings for all using (public.is_admin()) with check (public.is_admin());

-- Telefone de profissional não é público: o visitante lê só estas colunas.
revoke select on public.professionals from anon;
grant select (id, name, avatar, services, active, sort_order) on public.professionals to anon;

-- RPCs: visitantes podem agendar e ver horários ocupados (sem dados pessoais).
revoke all on function public.create_booking(text, text, text, bigint, bigint, date, time, text) from public;
revoke all on function public.get_busy(date, date) from public;
grant execute on function public.create_booking(text, text, text, bigint, bigint, date, time, text) to anon, authenticated;
grant execute on function public.get_busy(date, date) to anon, authenticated;


