-- 3 · REGRAS DE AGENDA ----------------------------------------

-- Lê um número de settings.data (ou o padrão, se faltar ou for inválido).
create or replace function public.cfg_int(k text, d integer)
returns integer
language sql
stable
set search_path = public
as $$
  select coalesce(
    (select case when (s.data ->> k) ~ '^-?[0-9]+(\.[0-9]+)?$'
                 then round((s.data ->> k)::numeric)::integer end
       from public.settings s where s.id = 1),
    d
  );
$$;

create or replace function public.cfg_bool(k text, d boolean)
returns boolean
language sql
stable
set search_path = public
as $$
  select coalesce(
    (select case lower(s.data ->> k)
              when 'true' then true when '1' then true
              when 'false' then false when '0' then false end
       from public.settings s where s.id = 1),
    d
  );
$$;

-- "Agora" no relógio do negócio (settings.tz). Fuso inválido → São Paulo.
create or replace function public.biz_now()
returns timestamp
language plpgsql
stable
set search_path = public
as $$
declare
  v_tz text := coalesce(nullif((select s.data ->> 'tz' from public.settings s where s.id = 1), ''), 'America/Sao_Paulo');
begin
  return now() at time zone v_tz;
exception when others then
  return now() at time zone 'America/Sao_Paulo';
end;
$$;

-- Trava única de agenda por data: serializa quem grava no mesmo dia,
-- então dois clientes nunca passam juntos pela checagem de conflito.
create or replace function public.lock_day(p_date date)
returns void
language sql
volatile
as $$
  select pg_advisory_xact_lock(hashtext('agenda:' || p_date::text));
$$;

-- Guarda de sobreposição. Vale para TODA escrita em bookings: o RPC público,
-- o agendamento manual do admin e as edições. Regra de conflito (com buffer):
--   início < outro.fim + buffer  E  fim > outro.início − buffer
-- Profissional nulo = agenda única do negócio (conflita com todos).
create or replace function public.bookings_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_buffer integer := greatest(public.cfg_int('buffer', 15), 0);
  v_s integer := public.mins(new.start_time);
  v_e integer := public.mins(new.end_time);
begin
  if new.status not in ('pending', 'confirmed') then
    return new;
  end if;

  -- Só confirmar/editar observação de um horário que já estava ativo: nada a checar.
  if tg_op = 'UPDATE'
     and old.status in ('pending', 'confirmed')
     and new.booking_date = old.booking_date
     and new.start_time = old.start_time
     and new.end_time = old.end_time
     and new.professional_id is not distinct from old.professional_id then
    return new;
  end if;

  perform public.lock_day(new.booking_date);

  if exists (
    select 1
      from public.bookings b
     where b.booking_date = new.booking_date
       and b.status in ('pending', 'confirmed')
       and b.id <> new.id
       and (new.professional_id is null or b.professional_id is null or b.professional_id = new.professional_id)
       and v_s < public.mins(b.end_time) + v_buffer
       and v_e > public.mins(b.start_time) - v_buffer
  ) then
    raise exception 'Horário indisponível.' using errcode = 'P0001', hint = 'slot_taken';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_bookings_guard on public.bookings;
create trigger trg_bookings_guard
  before insert or update on public.bookings
  for each row execute function public.bookings_guard();


-- 4 · RPCs PÚBLICAS -------------------------------------------

-- Horários ocupados, SEM dados pessoais: é o que o calendário do site precisa.
create or replace function public.get_busy(p_from date, p_to date)
returns table (booking_date date, start_time time, end_time time, professional_id bigint)
language sql
stable
security definer
set search_path = public
as $$
  select b.booking_date, b.start_time, b.end_time, b.professional_id
    from public.bookings b
   where b.status in ('pending', 'confirmed')
     and b.booking_date between p_from and least(p_to, p_from + 120)
   order by b.booking_date, b.start_time;
$$;

-- Cria um agendamento com validação completa no servidor.
-- Retorna { id, professional_id }. Erros vêm com hint (código para o front):
--   bad_name · bad_phone · bad_email · bad_slot · bad_service · bad_professional
--   too_soon · too_far · closed · blocked · limit · slot_taken
drop function if exists public.create_booking(text, text, text, bigint, bigint, date, time, text);
create or replace function public.create_booking(
  p_client_name      text,
  p_client_phone     text,
  p_client_email     text,
  p_service_id       bigint,
  p_professional_id  bigint,
  p_booking_date     date,
  p_start_time       time,
  p_notes            text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name    text := btrim(coalesce(p_client_name, ''));
  v_phone   text := regexp_replace(coalesce(p_client_phone, ''), '\D', '', 'g');
  v_email   text := lower(btrim(coalesce(p_client_email, '')));
  v_notes   text := left(btrim(coalesce(p_notes, '')), 500);
  v_buffer  integer := greatest(public.cfg_int('buffer', 15), 0);
  v_notice  integer := greatest(public.cfg_int('min_notice', 2), 0);
  v_adv     integer := greatest(public.cfg_int('max_advance', 60), 0);
  v_maxph   integer := greatest(public.cfg_int('max_per_phone', 3), 0);
  v_multi   boolean := public.cfg_bool('multiprof', false);
  v_now     timestamp := public.biz_now();
  v_svc     public.services%rowtype;
  v_bh      public.business_hours%rowtype;
  v_s       integer;
  v_e       integer;
  v_prof    bigint := null;
  v_id      bigint;
begin
  -- 1. Dados do cliente
  if char_length(v_name) < 2 or char_length(v_name) > 80 then
    raise exception 'Informe seu nome completo.' using errcode = 'P0001', hint = 'bad_name';
  end if;
  if length(v_phone) in (10, 11) then
    v_phone := '55' || v_phone;
  end if;
  if v_phone !~ '^55[1-9][0-9]{9,10}$' then
    raise exception 'Telefone inválido.' using errcode = 'P0001', hint = 'bad_phone';
  end if;
  if v_email <> '' and (char_length(v_email) > 120 or v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$') then
    raise exception 'E-mail inválido.' using errcode = 'P0001', hint = 'bad_email';
  end if;
  if p_booking_date is null or p_start_time is null then
    raise exception 'Escolha a data e o horário.' using errcode = 'P0001', hint = 'bad_slot';
  end if;

  -- 2. Serviço (duração e preço vêm do banco, nunca do navegador)
  select * into v_svc from public.services where id = p_service_id and active;
  if not found then
    raise exception 'Serviço indisponível.' using errcode = 'P0001', hint = 'bad_service';
  end if;
  v_s := public.mins(p_start_time);
  v_e := v_s + v_svc.duration_min;

  -- 3. Antecedência mínima e máxima (no relógio do negócio)
  if (p_booking_date + p_start_time) < v_now + make_interval(hours => v_notice) then
    raise exception 'Este horário já não pode ser reservado.' using errcode = 'P0001', hint = 'too_soon';
  end if;
  if p_booking_date > v_now::date + v_adv then
    raise exception 'Data além do limite de agendamento.' using errcode = 'P0001', hint = 'too_far';
  end if;

  -- 4. Expediente e intervalo
  select * into v_bh from public.business_hours where weekday = extract(dow from p_booking_date)::integer;
  if not found or not v_bh.open then
    raise exception 'Fechado neste dia.' using errcode = 'P0001', hint = 'closed';
  end if;
  if v_s < public.mins(v_bh.open_time) or v_e > public.mins(v_bh.close_time) then
    raise exception 'Fora do horário de funcionamento.' using errcode = 'P0001', hint = 'closed';
  end if;
  if v_bh.break_start is not null
     and v_s < public.mins(v_bh.break_end) and v_e > public.mins(v_bh.break_start) then
    raise exception 'Horário dentro do intervalo.' using errcode = 'P0001', hint = 'closed';
  end if;

  -- 5. Bloqueios gerais (feriado, folga do negócio)
  if exists (
    select 1 from public.blocked_dates bd
     where bd.professional_id is null
       and p_booking_date between bd.date and coalesce(bd.date_end, bd.date)
       and (bd.all_day or (v_s < public.mins(bd.end_time) and v_e > public.mins(bd.start_time)))
  ) then
    raise exception 'Data bloqueada.' using errcode = 'P0001', hint = 'blocked';
  end if;

  -- 6. Daqui em diante, ninguém mais grava neste dia até terminarmos.
  perform public.lock_day(p_booking_date);

  -- 7. Limite de agendamentos em aberto por telefone (anti-spam)
  if v_maxph > 0 and (
    select count(*) from public.bookings
     where client_phone = v_phone
       and status in ('pending', 'confirmed')
       and booking_date >= v_now::date
  ) >= v_maxph then
    raise exception 'Você já tem agendamentos em aberto. Fale com a gente pelo WhatsApp.' using errcode = 'P0001', hint = 'limit';
  end if;

  -- 8. Profissional: com vários, o escolhido precisa estar livre; "sem preferência"
  --    recebe quem estiver livre e com menos atendimentos no dia.
  if v_multi and exists (select 1 from public.professionals where active) then
    if p_professional_id is not null and not exists (
      select 1 from public.professionals where id = p_professional_id and active
    ) then
      raise exception 'Profissional indisponível.' using errcode = 'P0001', hint = 'bad_professional';
    end if;

    select p.id into v_prof
      from public.professionals p
     where p.active
       and (p_professional_id is null or p.id = p_professional_id)
       and (jsonb_array_length(p.services) = 0
            or p.services @> jsonb_build_array(p_service_id)
            or p.services @> jsonb_build_array(p_service_id::text))
       and not exists (
         select 1 from public.blocked_dates bd
          where bd.professional_id = p.id
            and p_booking_date between bd.date and coalesce(bd.date_end, bd.date)
            and (bd.all_day or (v_s < public.mins(bd.end_time) and v_e > public.mins(bd.start_time)))
       )
       and not exists (
         select 1 from public.bookings b
          where b.booking_date = p_booking_date
            and b.status in ('pending', 'confirmed')
            and (b.professional_id is null or b.professional_id = p.id)
            and v_s < public.mins(b.end_time) + v_buffer
            and v_e > public.mins(b.start_time) - v_buffer
       )
     order by (
         select count(*) from public.bookings b2
          where b2.booking_date = p_booking_date
            and b2.professional_id = p.id
            and b2.status in ('pending', 'confirmed')
       ), p.sort_order, p.id
     limit 1;

    if v_prof is null then
      raise exception 'Horário indisponível.' using errcode = 'P0001', hint = 'slot_taken';
    end if;
  end if;

  -- 9. Grava (o gatilho bookings_guard confere a sobreposição mais uma vez)
  insert into public.bookings (
    client_name, client_phone, client_email, service_id, professional_id,
    booking_date, start_time, end_time, price_snapshot, notes, status
  ) values (
    v_name, v_phone, v_email, v_svc.id, v_prof,
    p_booking_date, p_start_time, p_start_time + make_interval(mins => v_svc.duration_min),
    v_svc.price, v_notes, 'pending'
  )
  returning id into v_id;

  return jsonb_build_object('id', v_id, 'professional_id', v_prof);
end;
$$;


-- 5 · RLS E PERMISSÕES ----------------------------------------

alter table public.services        enable row level security;
