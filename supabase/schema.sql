-- Precisa existir ANTES das policies que a usam.
create or replace function public.is_admin()
returns boolean
language sql
stable
set search_path = public
as $$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin', false);
$$;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- 'HH:MM' → minutos desde 00:00. Toda conta de horário é feita em minutos
-- (nunca em "time", que dá a volta na meia-noite).
create or replace function public.mins(t time)
returns integer
language sql
immutable
as $$
  select (extract(hour from t) * 60 + extract(minute from t))::integer;
$$;


-- 1 · TABELAS -------------------------------------------------

-- Configurações gerais (linha única). Chaves usadas pelo servidor:
-- buffer, min_notice, max_advance, max_per_phone, multiprof, tz.
create table if not exists public.settings (
  id          integer primary key default 1 check (id = 1),
  data        jsonb not null default '{}'::jsonb,
  updated_at  timestamptz not null default now()
);

-- Serviços oferecidos. price = 0 aparece como "Sob consulta".
create table if not exists public.services (
  id            bigint generated by default as identity primary key,
  name          text not null check (char_length(name) between 2 and 120),
  description   text not null default '' check (char_length(description) <= 600),
  duration_min  integer not null check (duration_min between 15 and 480),
  price         numeric(12,2) not null default 0 check (price >= 0),
  image         jsonb default null,
  active        boolean not null default true,
  sort_order    integer not null default 0,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- Horário de funcionamento (0 = domingo … 6 = sábado). Uma linha por dia.
create table if not exists public.business_hours (
  weekday      integer primary key check (weekday between 0 and 6),
  open         boolean not null default true,
  open_time    time not null default '09:00',
  close_time   time not null default '18:00',
  break_start  time default null,
  break_end    time default null,
  updated_at   timestamptz not null default now(),
  constraint bh_close_after_open check (close_time > open_time),
  constraint bh_break_pair check ((break_start is null) = (break_end is null)),
  constraint bh_break_inside check (
    break_start is null
    or (break_end > break_start and break_start >= open_time and break_end <= close_time)
  )
);

-- Profissionais (ou recursos: "Box 1", "Sala 2"…).
-- services = ids dos serviços que atende. Lista vazia = atende todos.
create table if not exists public.professionals (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 2 and 80),
  avatar      jsonb default null,
  phone       text not null default '',
  services    jsonb not null default '[]'::jsonb check (jsonb_typeof(services) = 'array'),
  active      boolean not null default true,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- Bloqueios: um dia (date) ou um período (date → date_end), o dia inteiro
-- ou só um intervalo. professional_id preenchido = folga só daquela pessoa.
create table if not exists public.blocked_dates (
  id               bigint generated by default as identity primary key,
  date             date not null,
  date_end         date default null,
  all_day          boolean not null default true,
  start_time       time default null,
  end_time         time default null,
  professional_id  bigint default null references public.professionals(id) on delete cascade,
  reason           text not null default '' check (char_length(reason) <= 120),
  created_at       timestamptz not null default now(),
  constraint bd_range check (date_end is null or date_end >= date),
  constraint bd_times check (all_day or (start_time is not null and end_time is not null and end_time > start_time))
);

-- Agendamentos. client_phone guarda só dígitos, com 55 (ex.: 5583999990000).
create table if not exists public.bookings (
  id               bigint generated by default as identity primary key,
  client_name      text not null check (char_length(client_name) between 2 and 80),
  client_phone     text not null check (client_phone ~ '^[0-9]{10,13}$'),
  client_email     text not null default '' check (char_length(client_email) <= 120),
  service_id       bigint not null references public.services(id) on delete restrict,
  professional_id  bigint references public.professionals(id) on delete set null,
  booking_date     date not null,
  start_time       time not null,
  end_time         time not null,
  price_snapshot   numeric(12,2) not null default 0 check (price_snapshot >= 0),
  status           text not null default 'pending'
                   check (status in ('pending', 'confirmed', 'done', 'cancelled')),
  notes            text not null default '' check (char_length(notes) <= 500),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  constraint bk_end_after_start check (end_time > start_time)
);

create index if not exists bookings_date_status_idx on public.bookings (booking_date, status);
create index if not exists bookings_phone_idx on public.bookings (client_phone);
create index if not exists blocked_dates_date_idx on public.blocked_dates (date);


